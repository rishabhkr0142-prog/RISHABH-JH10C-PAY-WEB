import { NextResponse } from "next/server";
import { requireAdmin } from "@/lib/admin-guard";
import connectDB from "@/lib/db";
import Order from "@/models/Order";
import Product from "@/models/Product";
import { normalizeProductKey } from "@/lib/product-keys";

export const dynamic = "force-dynamic";

function inferProductKey(order, product) {
  const stored = normalizeProductKey(order?.productKey || product?.productKey);
  if (stored) return stored;

  const text = [
    product?.name,
    product?.slug,
    order?.productName,
  ]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();

  if (/\blib\b/.test(text) || text.includes("library")) return "lib";
  if (/\buid\b/.test(text)) return "uid";
  return "";
}

/**
 * GET /api/admin/orders/suspect-licenses
 *
 * Lists completed LIB Bypass orders whose key may have been generated with the
 * old single MANI_APP_ID (UID app). Admin can use this to manually re-issue
 * those keys for the correct app.
 */
export async function GET() {
  const guard = await requireAdmin();
  if (guard instanceof NextResponse) return guard;

  try {
    await connectDB();

    const orders = await Order.find({
      status: "completed",
      licenseKey: { $exists: true, $ne: "" },
    })
      .populate("product", "name slug productKey")
      .sort({ deliveredAt: -1, createdAt: -1 })
      .limit(500)
      .lean();

    const suspects = orders
      .map((order) => {
        const product = order.product && typeof order.product === "object"
          ? order.product
          : null;
        const productKey = inferProductKey(order, product);

        return {
          _id: String(order._id),
          productName: product?.name || order.productName || "Unknown product",
          productKey,
          plan: order.plan?.label || "",
          planDays: Number(order.plan?.days) || 0,
          discordId: order.discordId || order.userId || "",
          licenseKey: order.licenseKey,
          deliveredAt: order.deliveredAt || order.updatedAt || order.createdAt,
        };
      })
      .filter((order) => order.productKey === "lib");

    return NextResponse.json({
      ok: true,
      count: suspects.length,
      note:
        "LIB Bypass orders completed before per-product app mapping may hold a key generated by the UID app. Re-issue these keys on the LIB app, then update/refund manually.",
      orders: suspects,
    });
  } catch (err) {
    console.error("GET /api/admin/orders/suspect-licenses failed:", err);
    return NextResponse.json(
      { error: "Could not load suspect license orders." },
      { status: 500 }
    );
  }
}
